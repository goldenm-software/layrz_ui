/// Calendar Navigation namespace.
abstract mixin class LayrzCalendarLocalizations {
  /// Localized text for "Previous year" navigation button.
  String get calendarYearBack;

  /// Localized text for "Next year" navigation button.
  String get calendarYearNext;

  /// Localized text for "Previous month" navigation button.
  String get calendarMonthBack;

  /// Localized text for "Next month" navigation button.
  String get calendarMonthNext;

  /// Localized text for "Previous week" navigation button.
  String get calendarWeekBack;

  /// Localized text for "Next week" navigation button.
  String get calendarWeekNext;

  /// Localized text for "Previous day" navigation button.
  String get calendarDayBack;

  /// Localized text for "Next day" navigation button.
  String get calendarDayNext;

  /// Localized text for "Today" button — jumps to current date.
  String get calendarToday;

  /// Localized text for "View as year" view mode selector.
  String get calendarViewYear;

  /// Localized text for "View as month" view mode selector.
  String get calendarViewMonth;

  /// Localized text for "View as week" view mode selector.
  String get calendarViewWeek;

  /// Localized text for "View as day" view mode selector.
  String get calendarViewDay;

  /// Localized prefix for view mode selector: "View as".
  String get calendarViewAs;

  /// Localized text for "Pick a month" modal trigger.
  String get calendarPickMonth;
}
