/// Maximum width (logical pixels) for the extra-small breakpoint (xs).
/// Screens narrower than this value are treated as extra-small.
const double kExtraSmallGrid = 600;

/// Maximum width (logical pixels) for the small breakpoint (sm).
/// Screens between [kExtraSmallGrid] and this value are treated as small.
const double kSmallGrid = 960;

/// Maximum width (logical pixels) for the medium breakpoint (md).
/// Screens between [kSmallGrid] and this value are treated as medium.
const double kMediumGrid = 1264;

/// Maximum width (logical pixels) for the large breakpoint (lg).
/// Screens between [kMediumGrid] and this value are treated as large.
/// Screens wider than this value are treated as extra-large (xl).
const double kLargeGrid = 1904;
